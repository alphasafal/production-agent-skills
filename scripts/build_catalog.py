#!/usr/bin/env python3
"""Generate the two files people meet before they read anything else.

    install-index.tsv          what install.sh reads to resolve packs and skills
                               (plain TSV, so the installer needs no JSON parser)
    docs/prompt-cheatsheet.md  per skill: what to type, the slash command, what
                               comes back

Both are derived, never hand-edited:

  - packs and their skills      <- packs.json
  - skill names, descriptions   <- skills/*/SKILL.md frontmatter
  - slash commands              <- slash-commands/*.md
  - example prompts, artifacts  <- evaluations/activation/*.json (the same
                                   prompts the activation benchmark sends to a
                                   real agent)

Run after changing any of those:

    python scripts/build_catalog.py          # rewrite both files
    python scripts/build_catalog.py --check  # exit 1 if either is out of date (CI)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _lib import REPO_ROOT, Skill, discover_skills, load_packs  # noqa: E402
from build_marketplace import command_skills  # noqa: E402

INDEX = REPO_ROOT / "install-index.tsv"
CHEATSHEET = REPO_ROOT / "docs" / "prompt-cheatsheet.md"

INDEX_HEADER = (
    "# Generated by scripts/build_catalog.py from packs.json, skills/, slash-commands/ and\n"
    "# evaluations/activation/. Do not edit. Read by install.sh.\n"
    "# pack<TAB>name<TAB>title<TAB>space-separated skills\n"
    "# skill<TAB>name<TAB>slash command<TAB>a prompt that should trigger it\n"
)
PROMPTS_PER_SKILL = 3


def skill_commands() -> dict[str, str]:
    """Map each skill to its slash command, e.g. incident-responder -> /incident."""
    return {skill: "/" + Path(filename).stem for filename, skill in command_skills().items()}


def obvious_prompts(skill: Skill) -> list[str]:
    return [c["prompt"] for c in skill.eval_cases() if c["category"] == "positive-obvious"]


def artifacts(skill: Skill) -> list[str]:
    """Every output file the skill's positive cases expect, in first-seen order.

    Only names that look like files are kept ("PRD" or "rollback plan" describe a
    section of the answer, not something you can open afterwards).
    """
    seen: list[str] = []
    for case in skill.eval_cases():
        if not case["expected_activation"]:
            continue
        for name in case.get("expected_artifacts", []):
            if name.endswith(".md") and name not in seen:
                seen.append(name)
    return seen


def handoffs(skill: Skill) -> list[tuple[str, str]]:
    """(prompt, other skill) for negatives that belong to a different skill."""
    return [(c["prompt"], c["route_to"]) for c in skill.eval_cases() if c.get("route_to")]


def first_sentence(text: str) -> str:
    flat = " ".join(text.split())
    return flat.split(". ")[0].rstrip(".") + "."


def build_index() -> str:
    skills = discover_skills()
    commands = skill_commands()
    lines = [INDEX_HEADER.rstrip("\n")]
    for name, spec in load_packs().items():
        lines.append("\t".join(["pack", name, spec["title"], " ".join(spec["skills"])]))
    for skill in skills:
        prompts = obvious_prompts(skill)
        if not prompts:
            raise SystemExit(f"{skill.name}: no positive-obvious activation case to use as a starter prompt")
        fields = ["skill", skill.name, commands.get(skill.name, ""), prompts[0]]
        for value in fields:
            if "\t" in value or "\n" in value:
                raise SystemExit(f"{skill.name}: tab or newline in an index field: {value!r}")
        lines.append("\t".join(fields))
    return "\n".join(lines) + "\n"


def build_cheatsheet() -> str:
    skills = discover_skills()
    commands = skill_commands()
    packs = load_packs()
    out = [
        "<!-- Generated by scripts/build_catalog.py. Do not edit: change the skill, its",
        "     slash command or evaluations/activation/<skill>.json and re-run the script. -->",
        "",
        "# Prompt cheatsheet",
        "",
        "What to type to get each skill, and what you get back.",
        "",
        "You never have to name a skill. Describe the task in your own words and the",
        "agent loads the skill that matches. The prompts below are taken from",
        "[`evaluations/activation/`](../evaluations/activation/), the suite the",
        "activation benchmark sends to a real agent (latest recorded run:",
        "[results](../evaluations/results/README.md#activation-results)). If a skill",
        "does not load for your phrasing, run its slash command in Claude Code, or",
        "ask for it by name in any agent: *\"use the debugging-investigator skill\"*.",
        "",
        "| Skill | Command | In packs |",
        "|---|---|---|",
    ]
    for skill in skills:
        in_packs = [p for p, spec in packs.items() if skill.name in spec["skills"]]
        out.append(
            f"| [{skill.name}](#{skill.name}) | `{commands.get(skill.name, '')}` | "
            f"{', '.join(in_packs)} |"
        )
    for skill in skills:
        out += ["", f"## {skill.name}", "", first_sentence(skill.description), ""]
        facts = [f"**Command:** `{commands[skill.name]}`"] if skill.name in commands else []
        made = artifacts(skill)
        if made:
            facts.append("**Writes:** " + ", ".join(f"`{a}`" for a in made))
        facts.append(f"**Source:** [`skills/{skill.name}/`](../skills/{skill.name}/)")
        out += [" · ".join(facts), "", "Say something like:", ""]
        out += [f"- \"{p}\"" for p in obvious_prompts(skill)[:PROMPTS_PER_SKILL]]
        other = handoffs(skill)
        if other:
            out += ["", "Hands off to another skill:", ""]
            out += [f"- \"{prompt}\" → [{target}](#{target})" for prompt, target in other]
    return "\n".join(out) + "\n"


def expected() -> dict[Path, str]:
    return {INDEX: build_index(), CHEATSHEET: build_cheatsheet()}


def problems() -> list[str]:
    """Generated files that are missing or differ from what would be written."""
    return [
        str(path.relative_to(REPO_ROOT))
        for path, content in expected().items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = parser.parse_args()
    if args.check:
        stale = problems()
        if stale:
            print("Out of date — run: python scripts/build_catalog.py")
            for p in stale:
                print(f"  {p}")
            return 1
        print("install-index.tsv and docs/prompt-cheatsheet.md are up to date.")
        return 0
    for path, content in expected().items():
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
