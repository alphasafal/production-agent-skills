#!/usr/bin/env python3
"""Generate the Claude Code plugin marketplace from packs.json.

The marketplace offers one plugin with every skill and command, plus one plugin
per role pack containing just that pack's skills and their slash commands, so a
user can install exactly their role:

    /plugin install production-agent-skills@alphasafal-skills   # everything
    /plugin install sre@alphasafal-skills                       # one role

How the layout has to look for Claude Code to load it (verified by installing
each plugin from a local marketplace; `claude plugin list` must say "enabled"):

  - Every entry is `strict: true`. With `strict: false` the root
    `.claude-plugin/plugin.json` and the entry both count as declaring
    components and the pack fails to load ("conflicting manifests").
  - Commands live in `slash-commands/`, not the auto-discovered `commands/`,
    or every pack would also get all 12 commands. Entries name a commands
    *directory* (file lists were ignored), so each pack gets a generated copy
    of its commands in `plugin-packs/<pack>/commands/`.

Run after editing packs.json, adding a skill, or adding a command:

    python scripts/build_marketplace.py          # rewrite marketplace + pack command copies
    python scripts/build_marketplace.py --check  # exit 1 if anything is out of date (CI)
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _lib import REPO_ROOT, discover_skills, load_packs  # noqa: E402

MARKETPLACE = REPO_ROOT / ".claude-plugin" / "marketplace.json"
PLUGIN = REPO_ROOT / ".claude-plugin" / "plugin.json"
COMMANDS_DIR = REPO_ROOT / "slash-commands"
PACKS_DIR = REPO_ROOT / "plugin-packs"
COMMAND_SKILL_RE = re.compile(r"Use the `([a-z0-9-]+)` skill")
GENERATED_NOTE = "<!-- Generated by scripts/build_marketplace.py from slash-commands/. Do not edit. -->\n"


def command_skills() -> dict[str, str]:
    """Map each command file name to the skill it invokes."""
    out = {}
    for path in sorted(COMMANDS_DIR.glob("*.md")):
        m = COMMAND_SKILL_RE.search(path.read_text())
        if m:
            out[path.name] = m.group(1)
    return out


def pack_command_files() -> dict[Path, str]:
    """Every generated per-pack command file and the content it must have."""
    cmds = command_skills()
    files = {}
    for pack, spec in load_packs().items():
        for name, skill in cmds.items():
            if skill in spec["skills"]:
                src = (COMMANDS_DIR / name).read_text()
                # Keep the frontmatter first; put the generated note after it.
                head, sep, body = src.partition("\n---\n")
                files[PACKS_DIR / pack / "commands" / name] = head + sep + GENERATED_NOTE + body
    return files


def build() -> dict:
    plugin = json.loads(PLUGIN.read_text())
    skills = {s.name for s in discover_skills()}
    unknown = {c: s for c, s in command_skills().items() if s not in skills}
    if unknown:
        raise SystemExit(f"commands reference unknown skills: {unknown}")

    homepage = plugin["homepage"]
    entries = [{
        "name": plugin["name"],
        "version": plugin["version"],
        "source": "./",
        "strict": True,
        "description": plugin["description"],
        "homepage": homepage,
        "license": plugin["license"],
        "keywords": plugin["keywords"],
        "commands": "./slash-commands",
    }]
    for pack, spec in load_packs().items():
        entries.append({
            "name": pack,
            "version": plugin["version"],
            "source": "./",
            "strict": True,
            "description": f"{spec['title']} pack: {spec['description']} "
                           f"Skills: {', '.join(spec['skills'])}.",
            "homepage": homepage,
            "license": plugin["license"],
            "keywords": ["skills", pack] + [k for k in plugin["keywords"] if k != "skills"][:4],
            "skills": [f"./skills/{s}" for s in spec["skills"]],
            "commands": f"./plugin-packs/{pack}/commands",
        })
    return {
        "$schema": "https://json.schemastore.org/claude-code-marketplace.json",
        "name": "alphasafal-skills",
        "description": "Evaluated, portable Agent Skills for engineering, SRE, security, data and product "
                       "roles. Install everything, or just your role's pack.",
        "owner": plugin["author"],
        "plugins": entries,
    }


def problems() -> list[str]:
    """Differences between what's on disk and what build() would write."""
    out = []
    text = json.dumps(build(), indent=2, ensure_ascii=False) + "\n"
    if not MARKETPLACE.is_file() or MARKETPLACE.read_text() != text:
        out.append(str(MARKETPLACE.relative_to(REPO_ROOT)))
    expected = pack_command_files()
    for path, content in expected.items():
        if not path.is_file() or path.read_text() != content:
            out.append(str(path.relative_to(REPO_ROOT)))
    if PACKS_DIR.is_dir():
        for path in PACKS_DIR.rglob("*"):
            if path.is_file() and path not in expected:
                out.append(f"{path.relative_to(REPO_ROOT)} (stale)")
    return out


def write() -> None:
    MARKETPLACE.write_text(json.dumps(build(), indent=2, ensure_ascii=False) + "\n")
    expected = pack_command_files()
    if PACKS_DIR.is_dir():
        for path in sorted(PACKS_DIR.rglob("*"), reverse=True):
            if path.is_file() and path not in expected:
                path.unlink()
            elif path.is_dir() and not any(path.iterdir()):
                path.rmdir()
    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = parser.parse_args()
    if args.check:
        stale = problems()
        if stale:
            print("Out of date — run: python scripts/build_marketplace.py")
            for p in stale:
                print(f"  {p}")
            return 1
        print("marketplace.json and plugin-packs/ are up to date.")
        return 0
    write()
    print(f"Wrote {MARKETPLACE.relative_to(REPO_ROOT)} ({len(build()['plugins'])} plugins) "
          f"and {len(pack_command_files())} pack command files under plugin-packs/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
